// Generates public/sw.js with a cache version injected at build time.
// Runs in the build pipeline (see package.json "prebuild" + "build") so it
// executes on Vercel as well as locally.
//
// The version is CATALOG_DATE plus the deployed commit. It used to be the date
// alone, so a deploy that fixed prices without bumping CATALOG_DATE (it has
// happened) left every phone on the old worker: no "new prices" button, and
// the old cache kept. Now every deploy is a new worker.
//
// public/sw.js is generated, not source: it is git-ignored. The copy that used
// to be committed was weeks stale, because only a build rewrites it.
import { readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalog = readFileSync(join(root, "data", "catalog.ts"), "utf8");
const match = catalog.match(/CATALOG_DATE\s*=\s*"([^"]+)"/);
const date = match ? match[1] : "0";

function buildId() {
  const sha = process.env.VERCEL_GIT_COMMIT_SHA;
  if (sha) return sha.slice(0, 7);
  try {
    return execSync("git rev-parse --short HEAD", { cwd: root, stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim();
  } catch {
    return Date.now().toString(36);
  }
}
const version = `${date}-${buildId()}`;

const sw = `// AUTO-GENERATED by scripts/gen-sw.mjs — do not edit by hand.
// Cache version = CATALOG_DATE + deployed commit: every deploy => new key => old cache purged.
const CACHE = "maxis-${version}";

// Hashed build files never change under the same URL, so they can be served
// from cache. Everything else is fetched live.
function isStaticAsset(url) {
  return (
    url.origin === self.location.origin &&
    (url.pathname.startsWith("/_next/static/") ||
      url.pathname === "/manifest.webmanifest" ||
      url.pathname === "/icon.svg" ||
      url.pathname === "/favicon.ico")
  );
}

self.addEventListener("install", (e) => {
  e.waitUntil(
    caches.open(CACHE).then(async (c) => {
      await c.add("/manifest.webmanifest").catch(() => {});
      // Keep an offline copy of the app only when signed in. The worker often
      // installs on the login screen, and storing "/" then saved the login page
      // (a redirected response), which a browser refuses to show offline.
      const r = await fetch("/", { redirect: "manual", credentials: "same-origin" }).catch(() => null);
      if (r && r.ok) await c.put("/", r);
    })
  );
  self.skipWaiting();
});

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Signed out? Drop every cached page so a shared shop tablet keeps no offline
// copy of the price list. Posted by the sign-out helper (lib/sign-out.ts).
self.addEventListener("message", (e) => {
  if (e.data === "clear-caches") {
    e.waitUntil(caches.keys().then((keys) => Promise.all(keys.map((k) => caches.delete(k)))));
  }
});

self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  const url = new URL(e.request.url);

  // HTML: network-first so a fresh app shell always wins; fall back to cache offline.
  if (e.request.mode === "navigate") {
    e.respondWith(
      fetch(e.request)
        .then((r) => {
          // Only cache a real signed-in page. Without this check the login
          // screen (or a redirect to it) gets stored as the offline shell, and
          // worse, a shell cached while signed in would still be served after
          // the session expired.
          const isLogin = r.redirected || new URL(r.url).pathname === "/login";
          if (r.ok && !isLogin) {
            // Each page is kept under its own path. Storing every page as "/"
            // made opening /simple or /admin replace the main app's offline copy.
            const cp = r.clone();
            caches.open(CACHE).then((c) => c.put(url.pathname, cp));
          }
          return r;
        })
        .catch(() =>
          caches.match(url.pathname).then((hit) => hit || caches.match("/"))
        )
    );
    return;
  }

  // Page data (React Server Component requests), API calls and analytics are
  // not cached: they can carry signed-in content and must never be served
  // stale. Offline, the app falls back to a full page load, handled above.
  if (!isStaticAsset(url)) return;

  // Static assets: cache-first (fast, works offline), then fill cache on miss.
  e.respondWith(
    caches.match(e.request).then((cached) =>
      cached ||
      fetch(e.request).then((resp) => {
        if (resp.ok) {
          const cp = resp.clone();
          caches.open(CACHE).then((c) => c.put(e.request, cp));
        }
        return resp;
      })
    )
  );
});
`;

writeFileSync(join(root, "public", "sw.js"), sw);
console.log(`[gen-sw] wrote public/sw.js  (CACHE = maxis-${version})`);
